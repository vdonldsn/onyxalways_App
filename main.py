"""
OnyxAlways Orders — Backend
============================
Single-file FastAPI service for managing custom print/design orders.

Why single-file? For a solo business, fewer files = less cognitive load.
Everything (models, schemas, routes, app) lives here. If this grows past
~500 lines, split into modules: models.py / schemas.py / routes/.

Run locally:  uvicorn main:app --reload --host 0.0.0.0 --port 8000
API docs:     http://localhost:8000/docs   (auto-generated by FastAPI)
App UI:       http://localhost:8000/
"""

from __future__ import annotations

import csv
import io
import os
from collections import defaultdict
from datetime import datetime, date, timedelta
from decimal import Decimal
from enum import Enum
from pathlib import Path
from typing import Optional

from fastapi import FastAPI, HTTPException, Depends, status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse, StreamingResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field, ConfigDict
